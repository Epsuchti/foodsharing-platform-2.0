#!/usr/bin/env node
// Copies the bell titles (bell.<TYPE>) of the client catalog client/src/app/features/bells/i18n/<lang>.json into
// server/src/main/resources/i18n/bells/messages_<lang>.properties (+ messages.properties = de), so push and Telegram
// messages use the same wording (docs/conventions.md A23). BellMessagesSyncTest fails when they drift.
//
//   node scripts/sync-bell-messages.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(REPO, 'client/src/app/features/bells/i18n');
const TARGET = path.join(REPO, 'server/src/main/resources/i18n/bells');
const LANGS = ['de', 'en', 'gws', 'fr', 'it'];

const escape = (value) => value.replace(/\\/g, '\\\\').replace(/\n/g, '\\n');

fs.mkdirSync(TARGET, { recursive: true });
for (const lang of LANGS) {
  const catalog = JSON.parse(fs.readFileSync(path.join(SOURCE, `${lang}.json`), 'utf8'));
  const lines = ['# Generated by scripts/sync-bell-messages.mjs from the client bell catalog. Do not edit.'];
  for (const key of Object.keys(catalog).filter((k) => k.startsWith('bell.')).sort()) {
    lines.push(`${key}=${escape(catalog[key])}`);
  }
  const text = `${lines.join('\n')}\n`;
  fs.writeFileSync(path.join(TARGET, `messages_${lang}.properties`), text);
  if (lang === 'de') {
    fs.writeFileSync(path.join(TARGET, 'messages.properties'), text);
  }
}
console.log(`Bell messages synced to ${path.relative(REPO, TARGET)}`);
