#!/usr/bin/env bash
# Automated load test (D17.1, plan-m7 B7).
#
#   e2e/load/run.sh [--quick] [--no-docs]
#
# 1. starts the production Postgres service (server/deploy/compose.yaml + e2e/load/compose.load.yaml, project
#    foodsharing-load, fresh volume),
# 2. starts the packaged jar (server/target/foodsharing-platform-*.jar, must contain the client:
#    `cd server && ./mvnw -q clean package -DskipTests`) with the e2e profile (dev login, seed data, fixed clock)
#    against that Postgres,
# 3. runs e2e/load/k6/main.js in the grafana/k6 image (10 -> 100 VUs, 5 min; --quick = 30 s dry run),
# 4. writes e2e/load/results/summary.json + table.md and (unless --no-docs or --quick) docs/load-test.md.
# Exit code = k6's (99 when a threshold failed). Env: LOAD_PORT (18180), LOAD_PG_PORT (15433), K6_IMAGE, JAVA_OPTS.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
LOAD_DIR="${ROOT}/e2e/load"
OUT="${LOAD_DIR}/results"
K6_IMAGE="${K6_IMAGE:-grafana/k6:1.3.0}"
export LOAD_PORT="${LOAD_PORT:-18180}"
export LOAD_PG_PORT="${LOAD_PG_PORT:-15433}"
QUICK=false
DOCS=true
for arg in "$@"; do
  case "${arg}" in
    --quick) QUICK=true; DOCS=false ;;
    --no-docs) DOCS=false ;;
    *) echo "unknown argument ${arg}" >&2; exit 2 ;;
  esac
done

# compose.yaml interpolates the app's variables even when only postgres starts
export VERSION=unused
export POSTGRES_PASSWORD="${POSTGRES_PASSWORD:-load-$(openssl rand -hex 8)}"
COMPOSE=(docker compose --project-name foodsharing-load -f "${ROOT}/server/deploy/compose.yaml"
  -f "${LOAD_DIR}/compose.load.yaml")

JAR="$(ls -t "${ROOT}"/server/target/foodsharing-platform-*.jar 2> /dev/null | head -1 || true)"
[[ -n "${JAR}" ]] || { echo "no jar: cd server && ./mvnw -q clean package -DskipTests" >&2; exit 1; }
unzip -l "${JAR}" BOOT-INF/classes/static/index.html > /dev/null 2>&1 || { echo "${JAR} has no client (static/index.html)" >&2; exit 1; }

mkdir -p "${OUT}"
APP_PID=""
cleanup() {
  local status=$?
  [[ -n "${APP_PID}" ]] && kill "${APP_PID}" 2> /dev/null && wait "${APP_PID}" 2> /dev/null || true
  "${COMPOSE[@]}" down --volumes --remove-orphans > /dev/null 2>&1 || true
  exit "${status}"
}
trap cleanup EXIT

echo "==> Postgres (compose project foodsharing-load, 127.0.0.1:${LOAD_PG_PORT})"
"${COMPOSE[@]}" down --volumes --remove-orphans > /dev/null 2>&1 || true
"${COMPOSE[@]}" up -d --wait postgres > /dev/null

echo "==> App ${JAR##*/} on :${LOAD_PORT} (profile e2e, Postgres)"
# shellcheck disable=SC2086
E2E_PORT="${LOAD_PORT}" java ${JAVA_OPTS:-} -jar "${JAR}" \
  --spring.profiles.active=e2e \
  --server.port="${LOAD_PORT}" \
  --spring.datasource.url="jdbc:postgresql://127.0.0.1:${LOAD_PG_PORT}/foodsharing" \
  --spring.datasource.username=foodsharing \
  --spring.datasource.password="${POSTGRES_PASSWORD}" \
  --spring.datasource.hikari.maximum-pool-size=20 \
  --spring.h2.console.enabled=false \
  --logging.level.root=WARN \
  > "${OUT}/server.log" 2>&1 &
APP_PID=$!
for _ in $(seq 1 120); do
  if curl -fs "http://127.0.0.1:${LOAD_PORT}/actuator/health/readiness" > /dev/null 2>&1; then break; fi
  kill -0 "${APP_PID}" 2> /dev/null || { tail -20 "${OUT}/server.log" >&2; exit 1; }
  sleep 1
done
curl -fs "http://127.0.0.1:${LOAD_PORT}/actuator/health/readiness" > /dev/null || { echo "app not ready" >&2; exit 1; }

echo "==> Volume data (e2e/load/volume.sql)"
"${COMPOSE[@]}" exec -T postgres psql -U foodsharing -d foodsharing -v ON_ERROR_STOP=1 -q -t -A -F ' ' \
  < "${LOAD_DIR}/volume.sql" | tee "${OUT}/volume.txt"

SCALE=1
[[ "${QUICK}" == true ]] && SCALE=0.1
echo "==> k6 (${K6_IMAGE}, duration scale ${SCALE})"
set +e
docker run --rm --add-host=host.docker.internal:host-gateway \
  -v "${LOAD_DIR}/k6:/scripts:ro" -v "${OUT}:/out" \
  -e BASE_URL="http://host.docker.internal:${LOAD_PORT}" -e DURATION_SCALE="${SCALE}" -e OUT_DIR=/out \
  "${K6_IMAGE}" run --quiet --no-color "/scripts/${LOAD_SCRIPT:-main.js}"
K6_STATUS=$?
set -e

if [[ "${DOCS}" == true ]]; then
  # the hand-written "## Findings" section of docs/load-test.md survives a regeneration
  FINDINGS="$(sed -n '/^## Findings/,$p' "${ROOT}/docs/load-test.md" 2> /dev/null || true)"
  {
    echo "# Load test"
    echo
    echo "Generated by \`e2e/load/run.sh\` (D17.1) on $(date -u +%Y-%m-%dT%H:%MZ), commit \`$(git -C "${ROOT}" rev-parse --short HEAD)\`."
    echo "Script: \`e2e/load/k6/main.js\` (${K6_IMAGE}); raw summary: \`e2e/load/results/summary.json\` (not committed)."
    echo
    echo "**Machine:** $(uname -sm), $(sysctl -n machdep.cpu.brand_string 2> /dev/null || uname -p), $(java -version 2>&1 | head -1)."
    echo "k6, the jar and Postgres 17 (compose, Docker Desktop) share this one machine, so the numbers are a"
    echo "regression baseline for this laptop, not a capacity statement for the production host."
    echo
    echo "**Profile:** \`browse\` ramps 10 → 100 VUs (2 min), holds 100 VUs (2.5 min), ramps down (30 s); each"
    echo "iteration runs one weighted journey (landing, dashboard, store list, pickups, messaging incl. 10 % sends,"
    echo "forum, map + bubble, search, bells) and sleeps 0.5–1.5 s. \`churn\` signs ${CHURN_USERS:-3} seed users up for"
    echo "a future pickup and out again in a loop. Data: seed data on Postgres (e2e profile, fixed clock) plus"
    echo "\`e2e/load/volume.sql\` ($(tr '\n' ',' < "${OUT}/volume.txt" | sed 's/,$//; s/,/, /g') extra rows). The e2e profile"
    echo "disables the per-IP limit of \`/api/public/**\` (all k6 traffic comes from one IP)."
    echo "Thresholds: p95 < 200 ms and failed < 0.1 % overall and per endpoint."
    echo
    echo "k6 exit code: ${K6_STATUS} ($([[ ${K6_STATUS} -eq 0 ]] && echo 'all thresholds passed' || echo 'thresholds failed'))."
    echo
    cat "${OUT}/table.md"
    if [[ -n "${FINDINGS}" ]]; then
      echo
      echo "${FINDINGS}"
    fi
  } > "${ROOT}/docs/load-test.md"
  echo "==> docs/load-test.md written"
fi
exit "${K6_STATUS}"
