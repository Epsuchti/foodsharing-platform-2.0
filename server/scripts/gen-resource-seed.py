#!/usr/bin/env python3
"""Generates seed/changes/174-resource-seed.yaml (M6 B12, seed module 0056): 8 categories in five languages,
10 resources (6 of seed users, 4 commons of zuerich-stadt) and favourites of foodsaver@local. Run from the repo root."""
import os

OUT = os.path.join("server", "src", "main", "resources", "db", "seed", "changes", "174-resource-seed.yaml")
TS = "2026-10-01T10:00:00"
ZURICH = "00000010-0001-4000-8000-000000000040"


def uid(table, n):
    return f"00000056-{table:04d}-4000-8000-{n:012d}"


def user(n):
    return f"00000001-0001-4000-8000-{n:012d}"


CATEGORIES = [  # icon, de, en, gws, fr, it
    ("wrench", "Werkzeug", "Tools", "Wärchzüüg", "Outils", "Attrezzi"),
    ("cooking-pot", "Küche", "Kitchen", "Chuchi", "Cuisine", "Cucina"),
    ("truck", "Transport", "Transport", "Transport", "Transport", "Trasporto"),
    ("party-popper", "Veranstaltung", "Events", "Aalass", "Événements", "Eventi"),
    ("book", "Bücher", "Books", "Büecher", "Livres", "Libri"),
    ("sprout", "Garten", "Garden", "Garte", "Jardin", "Giardino"),
    ("cpu", "Technik", "Technology", "Technik", "Technique", "Tecnica"),
    ("package", "Sonstiges", "Other", "Suscht", "Autres", "Altro"),
]
LANGS = ["de", "en", "gws", "fr", "it"]

# (owner user number or None = commons, name, description, private, openness, categories (1-based), region)
RESOURCES = [
    (6, "Lastenvelo", "Lastenvelo mit Kiste, ideal für grössere Abholungen.", False, "ASK_FIRST", [3], None),
    (6, "Einkochtopf 20 l", "Grosser Topf zum Einkochen von Obst und Gemüse.", False, "FREE_TO_BORROW", [2], ZURICH),
    (7, "Akkubohrmaschine", "Mit zwei Akkus und Bitset.", True, "ASK_FIRST", [1, 7], None),
    (9, "Kühlbox 50 l", "Elektrische Kühlbox für Abholungen im Sommer.", False, "FREE_TO_BORROW", [3, 7], ZURICH),
    (10, "Kochbuch Resteküche", "Rezepte für gerettete Lebensmittel.", False, "GIVE_AWAY", [4, 2], None),
    (11, "Gartenschere", "Für den Gemeinschaftsgarten.", False, "FREE_TO_BORROW", [6], None),
    (None, "Festzelt 3x6 m", "Zelt für Stände und Feste, im Lager Altstetten.", False, "ASK_FIRST", [4], ZURICH),
    (None, "Waage bis 150 kg", "Plattformwaage zum Wiegen geretteter Ware.", False, "FREE_TO_BORROW", [1, 8], ZURICH),
    (None, "Infostand-Material", "Banner, Flyer und Tischdecke.", False, "ASK_FIRST", [4], ZURICH),
    (None, "Thermoboxen (6 Stück)", "Isolierboxen für Kühlware.", False, "FREE_TO_BORROW", [3, 2], ZURICH),
]
FAVOURITES = [(6, 4), (6, 7), (6, 8)]


def col(name, value, kind="value"):
    if value is None:
        return ""
    if kind == "valueBoolean":
        return f"              - column: {{name: {name}, valueBoolean: {'true' if value else 'false'}}}\n"
    if kind == "valueNumeric":
        return f"              - column: {{name: {name}, valueNumeric: {value}}}\n"
    escaped = str(value).replace('"', '\\"')
    return f"              - column: {{name: {name}, {kind}: \"{escaped}\"}}\n"


def insert(table, columns):
    body = f"        - insert:\n            tableName: {table}\n            columns:\n"
    body += col("version", 0, "valueNumeric") + col("created_at", TS, "valueDate") + col("updated_at", TS, "valueDate")
    for c in columns:
        body += col(*c)
    return body


def change_set(n, comment, inserts):
    return (f"  - changeSet:\n      id: seed-174-{n}\n      author: platform\n      context: seed\n"
            f"      comment: '{comment}'\n      changes:\n" + "".join(inserts))


cats, names = [], []
for i, (icon, *labels) in enumerate(CATEGORIES, start=1):
    cats.append(insert("resource_category", [("id", uid(1, i)), ("icon", icon), ("sort_order", i, "valueNumeric")]))
    for j, (lang, label) in enumerate(zip(LANGS, labels)):
        names.append(insert("resource_category_i18n", [("id", uid(2, i * 10 + j)), ("category_id", uid(1, i)),
                                                        ("language", lang), ("name", label)]))
res, links = [], []
link_n = 0
for i, (owner, name, desc, private, openness, categories, region) in enumerate(RESOURCES, start=1):
    res.append(insert("resource", [("id", uid(3, i)), ("owner_id", None if owner is None else user(owner)),
                                   ("region_id", region), ("name", name), ("description", desc),
                                   ("is_private", private, "valueBoolean"), ("openness", openness)]))
    for c in categories:
        link_n += 1
        links.append(insert("resource_category_link", [("id", uid(4, link_n)), ("resource_id", uid(3, i)),
                                                        ("category_id", uid(1, c))]))
favs = [insert("resource_favorite", [("id", uid(6, n)), ("user_id", user(u)), ("resource_id", uid(3, r))])
        for n, (u, r) in enumerate(FAVOURITES, start=1)]

text = ("# Generated by server/scripts/gen-resource-seed.py. Resource mosaic (M6 B12); ids: docs/seed-ids.md module 0056.\n"
        "databaseChangeLog:\n"
        + change_set(1, "Resource categories (5 languages).", cats + names)
        + change_set(2, "Resources: 6 of seed users, 4 commons of zuerich-stadt.", res + links)
        + change_set(3, "Favourites of foodsaver@local.", favs))
with open(OUT, "w", encoding="utf-8") as f:
    f.write(text)
print(f"wrote {OUT}")
