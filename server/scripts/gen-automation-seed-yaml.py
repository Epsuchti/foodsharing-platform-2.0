#!/usr/bin/env python3
"""Writes the seed changelogs 105/106/111 (loadUpdateData of db/seed/automation/*.csv). Re-run after column changes."""
import os

OUT = os.path.join(os.path.dirname(__file__), "..", "src", "main", "resources", "db", "seed", "changes")
BASE = [("id", "UUID"), ("version", "NUMERIC"), ("created_at", "STRING"), ("updated_at", "STRING"),
        ("created_by", "UUID"), ("updated_by", "UUID")]


def load(cs_id, comment, table, columns):
    lines = ["  - changeSet:", "      id: %s" % cs_id, "      author: platform", "      context: seed",
             "      runOnChange: true", "      comment: '%s'" % comment, "      changes:",
             "        - loadUpdateData:", "            tableName: %s" % table,
             "            file: ../automation/%s.csv" % table, "            relativeToChangelogFile: true",
             "            primaryKey: id", "            encoding: UTF-8", "            separator: ','",
             "            quotchar: '\"'", "            columns:"]
    for name, kind in BASE + columns:
        lines.append("              - column: {name: %s, type: %s}" % (name, kind))
    return "\n".join(lines) + "\n"


f105 = ("# Seed (M4 B4): pickup policies S-06 (live), S-01, S-02 (cleaning), S-04 (linked to S-01) and S-03 (all off),\n"
        "# excluded date, cleaning exemption for bieb and 40 audits of the last 7 days (cleaning Fairteiler: seed 180).\n"
        "# Generated by server/scripts/gen-automation-seed.py + gen-automation-seed-yaml.py; ids in docs/seed-ids.md (0022).\n"
        "databaseChangeLog:\n"
        "  # seed-105-1 and seed-105-6 (with dry_run) were replaced by seed-105-8 and seed-105-9 when changelog 191 dropped\n"
        "  # the column (decision 167).\n")
f105 += load("seed-105-8", "Pickup policies.", "pickup_policy", [
    ("store_id", "UUID"), ("enabled", "BOOLEAN"), ("gap_rule_enabled", "BOOLEAN"),
    ("minimum_gap_days", "NUMERIC"), ("cleaning_rule_enabled", "BOOLEAN"), ("experience_rule_enabled", "BOOLEAN"),
    ("public_holiday_rule_enabled", "BOOLEAN")])
f105 += load("seed-105-2", "Excluded dates.", "pickup_policy_excluded_date", [
    ("policy_id", "UUID"), ("excluded_date", "DATE")])
f105 += load("seed-105-3", "Linked-store rules.", "pickup_policy_linked_store", [
    ("policy_id", "UUID"), ("bidirectional", "BOOLEAN"), ("window_mode", "STRING"), ("window_days_before", "NUMERIC"),
    ("window_days_after", "NUMERIC"), ("grace_minutes", "NUMERIC"), ("message", "STRING"), ("mirror_of", "UUID")])
f105 += load("seed-105-4", "Linked-store members.", "pickup_policy_linked_store_member", [
    ("link_id", "UUID"), ("store_id", "UUID")])
f105 += load("seed-105-5", "Cleaning-rule exemptions.", "cleaning_rule_exemption", [
    ("region_id", "UUID"), ("user_id", "UUID"), ("reason", "STRING")])
f105 += load("seed-105-9", "Pickup-policy decisions of the last 7 days.", "pickup_policy_audit", [
    ("policy_id", "UUID"), ("store_id", "UUID"), ("region_id", "UUID"), ("user_id", "UUID"), ("pickup_at", "STRING"),
    ("decision", "STRING"), ("reasons", "STRING"), ("user_message", "STRING"),
    ("error", "STRING")])
open(os.path.join(OUT, "105-automation-pickup-policy-seed.yaml"), "w").write(f105)

