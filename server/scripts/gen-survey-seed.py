#!/usr/bin/env python3
"""Generates the survey seed (docs/seed-ids.md module 0046) deterministically.

Writes src/main/resources/db/seed/changes/139-survey-seed.yaml. Re-run after editing:
python3 server/scripts/gen-survey-seed.py
"""
import json
import os
from datetime import datetime, timedelta, timezone

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "main", "resources", "db", "seed")


def user(n):
    return "00000001-0001-4000-8000-%012d" % n


FOODSAVER, JUMPER, SLEEPY, BIEB, GUIDE, BOT, WELCOME, REPORTS, ORGA = (
    user(6), user(7), user(8), user(9), user(10), user(11), user(12), user(13), user(14))
S01, S02 = "00000020-0001-4000-8000-000000000001", "00000020-0001-4000-8000-000000000002"


def mid(table, n):
    return "00000046-%04d-4000-8000-%012d" % (table, n)


def ts(dt):
    return dt.strftime("%Y-%m-%dT%H:%M:%S")


def q(value):
    return json.dumps(str(value), ensure_ascii=False)


def column(name, value, kind="value"):
    if value is None:
        return None
    if kind == "bool":
        return "              - column: {name: %s, valueBoolean: %s}" % (name, "true" if value else "false")
    if kind == "num":
        return "              - column: {name: %s, valueNumeric: %s}" % (name, value)
    if kind == "date":
        return "              - column: {name: %s, valueDate: '%s'}" % (name, ts(value))
    return "              - column: {name: %s, value: %s}" % (name, q(value))


def insert(table, cols):
    lines = ["        - insert:", "            tableName: " + table, "            columns:"]
    lines += [c for c in cols if c]
    return "\n".join(lines)


def base(id_, created, by=None):
    return [column("id", id_), column("version", 0, "num"), column("created_at", created, "date"),
            column("updated_at", created, "date"), column("created_by", by)]


def changeset(n, comment, inserts):
    return "\n".join(["  - changeSet:", "      id: seed-139-%d" % n, "      author: platform", "      context: seed",
                      "      comment: %s" % q(comment), "      changes:"] + inserts)


def js(values):
    return json.dumps(values, ensure_ascii=False)


# (owner, title, description, coauthors, questions [(type, label, required, options)])
SURVEYS = [
    (BOT, "Zufriedenheit Abholungen 2026", "Wie zufrieden bist du mit den Abholungen bei diesem Betrieb?", [ORGA], [
        ("STORE", "Betrieb", True, []),
        ("SINGLE_CHOICE", "Wie zufrieden bist du insgesamt?", True,
         ["Sehr zufrieden", "Zufrieden", "Unzufrieden"]),
        ("MULTIPLE_CHOICE", "Was gerettet wird", False, ["Brot", "Gemüse", "Milchprodukte", "Fertiggerichte"]),
        ("BOOLEAN", "Ist die Kontaktperson freundlich?", True, []),
        ("TEXT", "Was sollen wir verbessern?", False, []),
    ]),
    (ORGA, "Kochgruppe Menüwünsche", "Was wollen wir als Nächstes kochen?", [], [
        ("MULTIPLE_CHOICE", "Gerichte", True, ["Suppe", "Curry", "Kuchen"]),
        ("TEXT", "Weitere Ideen", False, []),
    ]),
]
# respondent, store, answers per question index of survey 1
RESPONSES = [
    (JUMPER, S01, ["Sehr zufrieden", ["Brot", "Gemüse"], "true", "Mehr Abholtermine am Wochenende."]),
    (BIEB, S01, ["Zufrieden", ["Brot"], "true", None]),
    (GUIDE, S02, ["Sehr zufrieden", ["Brot", "Milchprodukte"], "true", "Alles bestens."]),
    (BOT, S02, ["Unzufrieden", [], "false", "Die Ware ist oft schon verdorben."]),
    (WELCOME, S01, ["Zufrieden", ["Gemüse"], "true", None]),
    (REPORTS, S02, ["Zufrieden", ["Fertiggerichte"], "true", None]),
]

created = datetime(2026, 10, 10, 8, 0, tzinfo=timezone.utc)
out = ["# Generated by server/scripts/gen-survey-seed.py (edit the script, then re-run it). Surveys, questions,",
       "# co-authors and responses (docs/seed-ids.md module 0046).",
       "databaseChangeLog:"]

rows, qids = [], []
qn, cn = 0, 0
for i, (owner, title, desc, coauthors, questions) in enumerate(SURVEYS, start=1):
    rows.append(insert("survey", base(mid(1, i), created, owner) + [
        column("owner_id", owner), column("title", title), column("description", desc)]))
    for co in coauthors:
        cn += 1
        rows.append(insert("survey_coauthor", base(mid(2, cn), created, owner) + [
            column("survey_id", mid(1, i)), column("user_id", co)]))
    ids = []
    for k, (type_, label, required, options) in enumerate(questions):
        qn += 1
        ids.append(mid(3, qn))
        rows.append(insert("survey_question", base(mid(3, qn), created, owner) + [
            column("survey_id", mid(1, i)), column("sort_order", k, "num"), column("type", type_),
            column("label", label), column("required", required, "bool"), column("options_json", js(options))]))
    qids.append(ids)
out.append(changeset(1, "2 surveys (bot with co-author orga and a STORE question; orga) with %d questions." % qn,
                     rows))

resp = []
an = 0
for n, (who, store, values) in enumerate(RESPONSES, start=1):
    at = created + timedelta(days=n, hours=n)
    resp.append(insert("survey_response", base(mid(4, n), at, who) + [
        column("survey_id", mid(1, 1)), column("user_id", who), column("store_id", store)]))
    answers = [[store]] + [[v] if isinstance(v, str) else v for v in values]
    for k, vals in enumerate(answers):
        if vals is None or vals == [None] or vals == []:
            continue
        an += 1
        resp.append(insert("survey_answer", base(mid(5, an), at, who) + [
            column("response_id", mid(4, n)), column("question_id", qids[0][k]), column("values_json", js(vals))]))
out.append(changeset(2, "%d responses to the satisfaction survey (foodsaver has not answered)." % len(RESPONSES),
                     resp))

with open(os.path.join(ROOT, "changes", "139-survey-seed.yaml"), "w", encoding="utf-8") as fh:
    fh.write("\n".join(out) + "\n")
print("questions:", qn, "responses:", len(RESPONSES), "answers:", an)
