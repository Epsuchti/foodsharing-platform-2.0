#!/usr/bin/env python3
"""Generates the report seed (M6 B8): db/seed/changes/167-report-seed.yaml.

Run from anywhere: python3 server/scripts/gen-report-seed.py
"""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "main", "resources", "db", "seed")
OUT = os.path.join(ROOT, "changes", "167-report-seed.yaml")

USERS = {"foodsaver": 6, "jumper": 7, "sleepy": 8, "bieb": 9, "guide": 10, "reports": 13}
ZUERICH = "00000010-0001-4000-8000-000000000040"
MEDIATION_GROUP = "00000011-0001-4000-8000-000000000025"
STORE_S01 = "00000020-0001-4000-8000-000000000001"


def user_id(key):
    return "00000001-0001-4000-8000-%012d" % USERS[key]


def seed_id(table, n):
    return "00000050-%04d-4000-8000-%012d" % (table, n)


# (n, reporter, reported, reason, reason_text, store, status, consequence, reminder_at, created, message)
REPORTS = [
    (1, "foodsaver", "jumper", "NO_SHOW", None, STORE_S01, "TO_DO", None, None, "2026-10-20T18:00:00",
     "Jumper hat sich für die Abholung am Montag eingetragen und ist ohne Abmeldung nicht erschienen."),
    (2, "bieb", "jumper", "LATE", None, STORE_S01, "TO_DO", None, None, "2026-10-22T19:30:00",
     "Zum dritten Mal in diesem Monat über 30 Minuten zu spät, die Filiale hat sich beschwert."),
    (3, "guide", "sleepy", "CANCELLATION", None, None, "IN_PROGRESS", None, None, "2026-10-10T08:15:00",
     "Sehr kurzfristige Austragungen bei mehreren Betrieben, das Team musste spontan Ersatz suchen."),
    (4, "foodsaver", "sleepy", "OTHER", "Unfreundlich am Telefon", None, "IN_PROGRESS", None, None,
     "2026-10-05T12:00:00", "Bei der Absprache einer Übergabe war der Ton am Telefon sehr unfreundlich."),
    (5, "bieb", "jumper", "SELLS", None, None, "MEDIATION", None, None, "2026-09-28T17:45:00",
     "Es gibt Hinweise, dass gerettete Lebensmittel auf einer Online-Plattform weiterverkauft werden."),
    (6, "guide", "jumper", "NO_SHOW", None, None, "COMPLETED", "Verwarnung ausgesprochen, Gespräch geführt.",
     None, "2026-09-01T09:00:00", "Nicht zur Einführungsabholung erschienen, keine Rückmeldung."),
    (7, "foodsaver", "sleepy", "LATE", None, None, "TO_DO", None, "2026-11-03T08:00:00", "2026-10-25T16:20:00",
     "Kam eine Stunde zu spät zur Abholung, der Betrieb war bereits geschlossen."),
]

# (n, report, author, created, body)
WALL = [
    (1, 3, "reports", "2026-10-11T10:00:00", "Habe sleepy angeschrieben und um eine Stellungnahme gebeten."),
    (2, 3, "reports", "2026-10-14T09:30:00", "Antwort erhalten: gesundheitliche Gründe, Gespräch nächste Woche."),
    (3, 4, "reports", "2026-10-06T15:00:00", "Rückfrage an foodsaver wegen genauem Zeitpunkt gestellt."),
]

HISTORY = []


def hist(n, when, actor, subject, action, secondary=None, field=None, old=None, new=None):
    HISTORY.append((n, when, actor, subject, action, secondary, field, old, new))


def col(name, value):
    if value is None:
        return None
    return '              - column: {name: %s, value: "%s"}' % (name, value.replace('"', '\\"'))


def date(name, value):
    return "              - column: {name: %s, valueDate: '%s'}" % (name, value)


def insert(table, cols):
    lines = ["        - insert:", "            tableName: %s" % table, "            columns:"]
    lines += [c for c in cols if c is not None]
    return "\n".join(lines)


def base(id_, created, created_by=None):
    return [col("id", id_), "              - column: {name: version, valueNumeric: 0}", date("created_at", created),
            date("updated_at", created), col("created_by", created_by)]


def changeset(n, comment, inserts):
    head = ["  - changeSet:", "      id: seed-167-%d" % n, "      author: platform", "      context: seed",
            "      comment: \"%s\"" % comment, "      changes:"]
    return "\n".join(head + inserts)


def main():
    out = ["# Generated by server/scripts/gen-report-seed.py (edit the script, then re-run it). Reports (module 0050).",
           "databaseChangeLog:"]
    team = [
        insert("region_admin", base("00000010-0003-4000-8000-000000000012", "2026-01-15T10:00:00") + [
            col("user_id", user_id("reports")), col("region_id", MEDIATION_GROUP)]),
        insert("region_membership", base("00000010-0002-4000-8000-000000000063", "2026-01-15T10:00:00") + [
            col("user_id", user_id("reports")), col("region_id", MEDIATION_GROUP),
            "              - column: {name: active, valueBoolean: true}", date("joined_at", "2026-01-15T10:00:00")]),
    ]
    out.append(changeset(1, "reports@local administers the mediation group of Zuerich Stadt (mediation team).", team))
    rows = []
    for (n, reporter, reported, reason, reason_text, store, status, consequence, reminder, created, message) in REPORTS:
        rid = seed_id(1, n)
        rows.append(insert("report", base(rid, created, user_id(reporter)) + [
            col("region_id", ZUERICH), col("reported_user_id", user_id(reported)),
            col("reporter_id", user_id(reporter)), col("reason", reason), col("reason_text", reason_text),
            col("message", message), col("store_id", store), col("status", status),
            col("consequence", consequence), date("reminder_at", reminder) if reminder else None]))
        hist(len(HISTORY) + 1, created, user_id(reporter), rid, "CREATED", user_id(reported))
        if status != "TO_DO":
            hist(len(HISTORY) + 1, created[:8] + "%02d" % min(int(created[8:10]) + 1, 28) + created[10:],
                 user_id("reports"), rid, "STATUS_CHANGED", user_id(reported), "status", "TO_DO", status)
        if consequence:
            hist(len(HISTORY) + 1, "2026-09-10T10:00:00", user_id("reports"), rid, "CONSEQUENCE_SET",
                 user_id(reported), "consequence", None, consequence)
        if reminder:
            hist(len(HISTORY) + 1, "2026-10-26T09:00:00", user_id("reports"), rid, "REMINDER_SET",
                 user_id(reported), "reminderAt", None, reminder + "Z")
    out.append(changeset(2, "7 reports in Zuerich Stadt (jumper, sleepy), two about store S-01.", rows))
    posts = []
    for (n, report, author, created, body) in WALL:
        posts.append(insert("report_wall_post", base(seed_id(2, n), created, user_id(author)) + [
            col("report_id", seed_id(1, report)), col("author_id", user_id(author)), col("body", body)]))
        hist(len(HISTORY) + 1, created, user_id(author), seed_id(1, report), "WALL_POST_CREATED")
    out.append(changeset(3, "Wall posts of the report team on two IN_PROGRESS reports.", posts))
    mediation = [insert("mediation_request", base(seed_id(3, 1), "2026-10-18T20:00:00", user_id("foodsaver")) + [
        col("region_id", ZUERICH), col("requester_id", user_id("foodsaver")),
        col("counterpart_user_id", user_id("jumper")),
        col("message", "Wir haben wiederholt Streit bei Übergaben und würden gern gemeinsam eine Lösung finden.")])]
    hist(len(HISTORY) + 1, "2026-10-18T20:00:00", user_id("foodsaver"), seed_id(3, 1), "MEDIATION_REQUESTED",
         user_id("foodsaver"))
    out.append(changeset(4, "One mediation request (foodsaver about jumper).", mediation))
    entries = []
    for (n, when, actor, subject, action, secondary, field, old, new) in HISTORY:
        entries.append(insert("history_entry", base(seed_id(4, n), when, actor) + [
            date("occurred_at", when), col("actor_id", actor), col("actor_type", "USER"),
            col("subject_type", "REPORT"), col("subject_id", subject), col("secondary_subject_id", secondary),
            col("action", action), col("field", field), col("old_value", old), col("new_value", new),
            col("region_id", ZUERICH)]))
    out.append(changeset(5, "Report log entries (D10.3).", entries))
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", OUT, len(HISTORY), "history entries")


if __name__ == "__main__":
    main()
