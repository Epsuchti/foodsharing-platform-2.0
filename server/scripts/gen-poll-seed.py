#!/usr/bin/env python3
"""Generates the poll seed (docs/seed-ids.md module 0045) deterministically.

Writes src/main/resources/db/seed/changes/138-poll-seed.yaml. Re-run after editing:
python3 server/scripts/gen-poll-seed.py
"""
import json
import os
from datetime import datetime, timezone

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "main", "resources", "db", "seed")


def user(n):
    return "00000001-0001-4000-8000-%012d" % n


FOODSAVER, JUMPER, SLEEPY, BIEB, GUIDE, BOT, WELCOME, REPORTS, ORGA = (
    user(6), user(7), user(8), user(9), user(10), user(11), user(12), user(13), user(14))
ZUERICH = "00000010-0001-4000-8000-000000000040"
VOTING_GROUP = "00000011-0001-4000-8000-000000000021"
KOCH = "00000011-0001-4000-8000-000000000033"
VALUES = {"SELECT_ONE": [1], "SELECT_MULTIPLE": [1], "THUMBS": [1, 0, -1], "SCORE": [3, 2, 1, 0, -1, -2, -3]}


def mid(table, n):
    return "00000045-%04d-4000-8000-%012d" % (table, n)


def ts(dt):
    return dt.strftime("%Y-%m-%dT%H:%M:%S")


def q(value):
    return json.dumps(str(value), ensure_ascii=False)


def column(name, value, kind="value"):
    if value is None:
        return None
    if kind == "bool":
        return "              - column: {name: %s, valueBoolean: %s}" % (name, "true" if value else "false")
    if kind == "num":
        return "              - column: {name: %s, valueNumeric: %s}" % (name, value)
    if kind == "date":
        return "              - column: {name: %s, valueDate: '%s'}" % (name, ts(value))
    return "              - column: {name: %s, value: %s}" % (name, q(value))


def insert(table, cols):
    lines = ["        - insert:", "            tableName: " + table, "            columns:"]
    lines += [c for c in cols if c]
    return "\n".join(lines)


def base(id_, created, by=None):
    return [column("id", id_), column("version", 0, "num"), column("created_at", created, "date"),
            column("updated_at", created, "date"), column("created_by", by)]


def changeset(n, comment, inserts):
    return "\n".join(["  - changeSet:", "      id: seed-138-%d" % n, "      author: platform", "      context: seed",
                      "      comment: %s" % q(comment), "      changes:"] + inserts)


def utc(y, mo, d, h, mi=0):
    return datetime(y, mo, d, h, mi, tzinfo=timezone.utc)


# name, region, author, type, scope, starts, ends, eligible, options, {option: {value: votes}}, voters,
# start_notified, end_notified, cancelled_at, description
POLLS = [
    ("Wo soll der nächste Stammtisch stattfinden?", ZUERICH, BOT, "SELECT_ONE", "FOODSAVERS",
     utc(2026, 10, 30, 8), utc(2026, 11, 9, 20), 9,
     ["Quartierzentrum Kreis 4", "Café Zähringer", "Gemeinschaftsgarten Wiedikon", "Online"],
     {0: {1: 2}, 1: {1: 3}, 2: {1: 1}}, [JUMPER, BIEB, GUIDE, BOT, WELCOME, REPORTS],
     utc(2026, 10, 30, 8, 15), None, None, "Bitte stimmt bis Montag ab – der Stammtisch ist am 20. November."),
    ("Bewertung der Hygieneschulung", ZUERICH, BOT, "SCORE", "VERIFIED_FOODSAVERS",
     utc(2026, 10, 15, 8), utc(2026, 10, 25, 20), 9,
     ["Inhalt", "Dauer", "Unterlagen"],
     {0: {3: 2, 2: 2, 1: 1}, 1: {0: 2, 1: 1, -1: 1, -2: 1}, 2: {3: 1, 2: 1, 0: 1, -1: 1, -3: 1}},
     [FOODSAVER, JUMPER, BIEB, GUIDE, BOT], utc(2026, 10, 15, 8, 15), utc(2026, 10, 24, 20, 15), None,
     "Wie fandet ihr die Schulung vom Oktober? −3 = gar nicht gut, 3 = sehr gut."),
    ("Neue Fairteiler-Standorte", ZUERICH, BOT, "THUMBS", "FOODSAVERS",
     utc(2026, 11, 10, 8), utc(2026, 11, 20, 20), 9,
     ["Bahnhof Altstetten", "Universität Irchel", "Hardplatz"], {}, [], None, None, None,
     "Daumen hoch, wenn du einen Fairteiler an diesem Ort betreuen würdest."),
    ("Termine Weihnachtsmarkt", ZUERICH, BOT, "SELECT_MULTIPLE", "VERIFIED_FOODSAVERS_HOME_REGION",
     utc(2026, 10, 20, 8), utc(2026, 10, 22, 10), 9,
     ["Samstag, 5. Dezember", "Sonntag, 6. Dezember", "Samstag, 12. Dezember"], {}, [],
     utc(2026, 10, 20, 8, 15), None, utc(2026, 10, 22, 10), "Abgebrochen: Der Stand findet nicht statt."),
    ("Was kochen wir im Dezember?", KOCH, FOODSAVER, "SELECT_MULTIPLE", "FOODSAVERS",
     utc(2026, 10, 31, 8), utc(2026, 11, 7, 20), 2,
     ["Brotsuppe", "Gemüsecurry", "Bananenbrot"], {0: {1: 1}, 2: {1: 1}}, [JUMPER],
     utc(2026, 10, 31, 8, 15), None, None, None),
]

created = datetime(2026, 10, 1, 8, 0, tzinfo=timezone.utc)
out = ["# Generated by server/scripts/gen-poll-seed.py (edit the script, then re-run it). Polls, options, aggregated",
       "# votes and voters (docs/seed-ids.md module 0045). bot administrates the zuerich-stadt VOTING group (21).",
       "databaseChangeLog:"]

out.append(changeset(1, "bot administrates the zuerich-stadt VOTING group (may create zuerich-stadt polls).", [
    insert("region_admin", base(mid(5, 1), created) + [column("user_id", BOT), column("region_id", VOTING_GROUP)])]))

polls, options, values, votes = [], [], [], []
on, vn, vote_n = 0, 0, 0
for i, (name, region, author, type_, scope, starts, ends, eligible, opts, agg, voters, start_n, end_n, cancelled,
        desc) in enumerate(POLLS, start=1):
    pid = mid(1, i)
    polls.append(insert("poll", base(pid, created, author) + [
        column("region_id", region), column("author_id", author), column("name", name), column("description", desc),
        column("scope", scope), column("type", type_), column("starts_at", starts, "date"),
        column("ends_at", ends, "date"), column("shuffle_options", i == 1, "bool"),
        column("eligible_count", eligible, "num"), column("vote_count", len(voters), "num"),
        column("cancelled_by", BOT if cancelled else None), column("cancelled_at", cancelled, "date"),
        column("start_notified_at", start_n, "date"), column("end_notified_at", end_n, "date")]))
    for k, text in enumerate(opts):
        on += 1
        options.append(insert("poll_option", base(mid(2, on), created, author) + [
            column("poll_id", pid), column("option_index", k, "num"), column("option_text", text)]))
        for value in VALUES[type_]:
            vn += 1
            values.append(insert("poll_option_value", base(mid(3, vn), created, author) + [
                column("poll_id", pid), column("option_index", k, "num"), column("option_value", value, "num"),
                column("votes", agg.get(k, {}).get(value, 0), "num")]))
    for k, voter in enumerate(voters):
        vote_n += 1
        at = starts.replace(hour=12) if starts.hour < 12 else starts
        votes.append(insert("poll_vote", base(mid(4, vote_n), at, voter) + [
            column("poll_id", pid), column("user_id", voter), column("voted_at", at, "date")]))
out.append(changeset(2, "5 polls (zuerich-stadt: running SELECT_ONE, ended SCORE, upcoming THUMBS, cancelled "
                        "SELECT_MULTIPLE; kochgruppe: running SELECT_MULTIPLE) with %d options." % on,
                     polls + options + values))
out.append(changeset(3, "%d voters (who voted, never what)." % vote_n, votes))

with open(os.path.join(ROOT, "changes", "138-poll-seed.yaml"), "w", encoding="utf-8") as fh:
    fh.write("\n".join(out) + "\n")
print("polls:", len(POLLS), "options:", on, "values:", vn, "votes:", vote_n)
