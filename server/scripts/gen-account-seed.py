"""Generates the account seed of M6 B3/B4 deterministically (docs/seed-ids.md).

Writes
- src/main/resources/db/seed/changes/161-user-seed-account.yaml: a pending email change of profile@local
  (raw tokens below, so e2e tests and developers can confirm/abort it),
- src/main/resources/db/seed/changes/162-upload-seed-avatars.yaml + db/seed/upload/files/avatar-<key>.png: one
  512 px PNG avatar per seed user (uploads 00000040-0001-...-0101..0114, claimed as USER_PHOTO, public); the sm/md/lg
  variants are rendered on first start by UploadSeedFiles,
- src/main/resources/db/seed/changes/176-calendar-seed.yaml: the calendar token of foodsaver@local.
Re-run after editing: python3 server/scripts/gen-account-seed.py
"""
import hashlib
import os
import struct
import zlib

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "main", "resources", "db", "seed")
CHANGES = os.path.join(ROOT, "changes")
FILES = os.path.join(ROOT, "upload", "files")

USERS = ["newbie", "profile", "quiz", "einab1", "pending", "foodsaver", "jumper", "sleepy", "bieb", "guide", "bot",
         "welcome", "reports", "orga"]
COLORS = [(0x25, 0x83, 0x4a), (0x1e, 0x6f, 0xa8), (0x8e, 0x44, 0xad), (0xd3, 0x54, 0x00), (0xc0, 0x39, 0x2b),
          (0x16, 0xa0, 0x85), (0x2c, 0x3e, 0x50), (0x7f, 0x8c, 0x8d), (0xb7, 0x95, 0x0b), (0x27, 0xae, 0x60),
          (0x29, 0x80, 0xb9), (0x9b, 0x59, 0xb6), (0xe6, 0x7e, 0x22), (0x34, 0x49, 0x5e)]
SIZE = 512
CREATED = "2026-09-01T08:00:00"

EMAIL_CHANGE_TOKEN = "seed-email-change-confirm-profile"
EMAIL_CHANGE_ABORT_TOKEN = "seed-email-change-abort-profile"
CALENDAR_TOKEN = "0123456789abcdef" * 4


def user_id(n):
    return "00000001-0001-4000-8000-%012d" % n


def sha(text):
    return hashlib.sha256(text.encode()).hexdigest()


def png(color):
    """Head-and-shoulders silhouette in a light tint on a coloured background."""
    light = tuple(min(255, c + (255 - c) * 7 // 10) for c in color)
    rows = []
    cx, head_y, head_r = SIZE / 2, SIZE * 0.38, SIZE * 0.17
    body_y, body_rx, body_ry = SIZE * 0.95, SIZE * 0.33, SIZE * 0.3
    for y in range(SIZE):
        row = bytearray(b"\x00")
        for x in range(SIZE):
            in_head = (x - cx) ** 2 + (y - head_y) ** 2 <= head_r ** 2
            in_body = ((x - cx) / body_rx) ** 2 + ((y - body_y) / body_ry) ** 2 <= 1
            row += bytes(light if in_head or in_body else color)
        rows.append(bytes(row))
    raw = zlib.compress(b"".join(rows), 9)

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", SIZE, SIZE, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", raw) + chunk(b"IEND", b""))


def col(name, value, kind="value"):
    if isinstance(value, (int, float)) and kind == "value":
        return "              - column: {name: %s, valueNumeric: %s}\n" % (name, value)
    return "              - column: {name: %s, %s: \"%s\"}\n" % (name, kind, value)


def write(name, header, body):
    with open(os.path.join(CHANGES, name), "w") as f:
        f.write("# Generated by server/scripts/gen-account-seed.py (edit the script, then re-run it). %s\n" % header)
        f.write("databaseChangeLog:\n" + body)


def changeset(cid, comment):
    return ("  - changeSet:\n      id: %s\n      author: platform\n      context: seed\n      comment: \"%s\"\n"
            "      changes:\n" % (cid, comment))


# 161: pending email change of profile@local (requested 2026-11-02 09:00, valid 24 h from the seed date on)
body = changeset("seed-161-1", "Pending email change of profile@local (tokens in the generator script).")
body += "        - insert:\n            tableName: email_change\n            columns:\n"
body += col("id", "00000001-0006-4000-8000-000000000001")
body += col("version", 0)
body += col("created_at", "2026-11-02T09:00:00", "valueDate")
body += col("updated_at", "2026-11-02T09:00:00", "valueDate")
body += col("user_id", user_id(2))
body += col("old_email", "profile@local")
body += col("new_email", "noah.keller@local.test")
body += col("token_hash", sha(EMAIL_CHANGE_TOKEN))
body += col("abort_token_hash", sha(EMAIL_CHANGE_ABORT_TOKEN))
body += col("expires_at", "2099-12-31T00:00:00", "valueDate")
write("161-user-seed-account.yaml", "Pending email change (module 0001 code 0006).", body)

# 162: avatar uploads
os.makedirs(FILES, exist_ok=True)
body = changeset("seed-162-1", "Avatar uploads of the 14 seed users (variants rendered by UploadSeedFiles).")
updates = changeset("seed-162-2", "Seed users use their avatar upload as profile photo.")
for i, key in enumerate(USERS, start=1):
    data = png(COLORS[i - 1])
    file_name = "avatar-%s.png" % key
    with open(os.path.join(FILES, file_name), "wb") as f:
        f.write(data)
    upload_id = "00000040-0001-4000-8000-%012d" % (100 + i)
    body += "        - insert:\n            tableName: upload\n            columns:\n"
    body += col("id", upload_id)
    body += col("version", 0)
    body += col("created_at", CREATED, "valueDate")
    body += col("updated_at", CREATED, "valueDate")
    body += col("owner_user_id", user_id(i))
    body += col("file_name", file_name)
    body += col("mime_type", "image/png")
    body += col("size", len(data))
    body += col("sha256", hashlib.sha256(data).hexdigest())
    body += col("storage_key", "seed/" + file_name)
    body += col("usage_count", 1)
    body += col("usage_module", "USER_PHOTO")
    body += col("usage_owner_id", user_id(i))
    body += col("width", SIZE)
    body += col("height", SIZE)
    body += "              - column: {name: is_public, valueBoolean: true}\n"
    updates += "        - update:\n            tableName: user_account\n            columns:\n"
    updates += col("photo_upload_id", upload_id)
    updates += col("avatar_url", "/api/uploads/%s?size=md" % upload_id)
    updates += "            where: \"id = '%s'\"\n" % user_id(i)
write("162-upload-seed-avatars.yaml", "Avatar uploads (module 0040, ids ...0101-0114).", body + updates)

# 176: calendar token of foodsaver@local
body = changeset("seed-176-1", "Calendar feed token of foodsaver@local.")
body += "        - insert:\n            tableName: calendar_token\n            columns:\n"
body += col("id", "00000047-0001-4000-8000-000000000001")
body += col("version", 0)
body += col("created_at", CREATED, "valueDate")
body += col("updated_at", CREATED, "valueDate")
body += col("user_id", user_id(6))
body += col("token", CALENDAR_TOKEN)
write("176-calendar-seed.yaml", "Calendar token (module 0047).", body)
print("ok")
